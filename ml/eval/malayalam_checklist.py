"""Write docs/MALAYALAM_CHECK.md: every fixed Malayalam phrase the host hears, for a fluent speaker to check.

    python -m eval.malayalam_checklist

Generated from the code (server prompts, read-back framing, number and time words), so it
stays in sync. Re-run after changing any of them.
"""
from __future__ import annotations

import importlib.util

from pipeline import READBACK_INTRO, READBACK_OUTRO, config
from pipeline.ml_numbers import speakable, to_words

REPO = config.ML.parent
OUT = REPO / 'docs' / 'MALAYALAM_CHECK.md'

NUMBERS = [1, 2, 7, 9, 12, 21, 50, 99, 150, 250, 300, 500, 800, 1000, 1500, 2000, 2500, 12000, 50000, 150000]
TIMES = ['9am', '12 pm', '1pm', '3:30 pm', '6 pm']


def load_prompts() -> dict[str, tuple[str, str]]:
    spec = importlib.util.spec_from_file_location('prompts', REPO / 'server' / 'app' / 'prompts.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.PROMPTS


def main() -> None:
    lines = [
        '# Malayalam check',
        '',
        'Every fixed Malayalam phrase the host reads or hears. A fluent speaker should check each one, '
        'mark ✅ or write the correction, and the team updates the code. '
        'Generated by `python -m eval.malayalam_checklist`; do not edit by hand.',
        '',
        '## Bot prompts (`server/app/prompts.py`)',
        '',
        '| ✅ | Key | Malayalam | Meant to say |',
        '|---|---|---|---|',
    ]
    for key, (ml, en) in load_prompts().items():
        lines.append(f'| | `{key}` | {ml} | {en} |')
    lines += [
        '',
        '## Read-back framing (`ml/pipeline/__init__.py`)',
        '',
        '| ✅ | Where | Malayalam | Meant to say |',
        '|---|---|---|---|',
        f'| | Before the listing | {READBACK_INTRO} | This is what tourists will see. |',
        f'| | After the listing | {READBACK_OUTRO} | If this is right, send a thumbs up. To correct it, send a new voice note. |',
        '',
        '## Numbers and times as spoken (`ml/pipeline/ml_numbers.py`)',
        '',
        'The read-back voice cannot say digits, so prices and times are spelled out first.',
        '',
        '| ✅ | Written | Spoken |',
        '|---|---|---|',
    ]
    lines += [f'| | {n} | {to_words(n)} |' for n in NUMBERS]
    lines += [f'| | {t} | {speakable(t)} |' for t in TIMES]
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
