"""Write ml/eval/results.md from the eval results (for the README and the metrics slide).

    python -m eval.report

Reads eval/results/*.json written by eval.asr_fleurs and eval.listing_eval, and measures
model sizes on disk. Re-run after any eval.
"""
from __future__ import annotations

import json
import platform
from pathlib import Path

from pipeline import config
from pipeline.models import asr_dir, llm_path, mb, nllb_dir, tts_dir

RESULTS = config.ML / 'eval' / 'results'
OUT = config.ML / 'eval' / 'results.md'

MODELS = [
    ('Speech to text', config.ASR_MODEL, 'Whisper fine-tuned on Malayalam, CTranslate2 int8', 'Apache-2.0', asr_dir),
    ('Translation', config.NLLB_MODEL, 'ml→en, en→de, en→ml; CTranslate2 int8', 'CC-BY-NC-4.0 (non-commercial)', nllb_dir),
    ('Listing writer', f'{config.LLM_REPO} ({config.LLM_FILE})', 'llama.cpp, JSON schema', 'Apache-2.0', llm_path),
    ('Read-back voice', config.TTS_MODEL, 'VITS', 'CC-BY-NC-4.0 (non-commercial)', tts_dir),
    ('Prompt voice (English, demo)', config.TTS_MODEL_EN, 'VITS', 'CC-BY-NC-4.0 (non-commercial)', lambda: tts_dir(config.TTS_MODEL_EN)),
]


def load(name: str) -> dict | None:
    path = RESULTS / name
    return json.loads(path.read_text(encoding='utf-8')) if path.exists() else None


def main() -> None:
    lines = ['# Engine results', '',
             f'Generated by `python -m eval.report`. Machine: {platform.processor() or platform.machine()}, '
             f'{config.CPU_THREADS} threads, CPU only.', '']

    total = 0.0
    lines += ['## Models', '', '| Job | Model | Notes | Licence | Size |', '|---|---|---|---|---|']
    for job, name, notes, licence, path in MODELS:
        size = mb(path())
        total += size
        lines.append(f'| {job} | `{name}` | {notes} | {licence} | {size:.0f} MB |')
    lines += [f'| **Total** | | | | **{total:.0f} MB** |', '']

    asr = sorted(RESULTS.glob('asr_fleurs_*.json'), key=lambda p: int(p.stem.rsplit('_n', 1)[1]))
    lines += ['## Speech to text: FLEURS Malayalam (test split)', '',
              'Clean read speech, so real outdoor voice notes will do worse. Malayalam fuses words, so one wrong '
              'letter makes a whole word wrong: character error rate (CER) is the fairer number.', '',
              '| Model | Clips | CER | WER | Median seconds per clip |', '|---|---|---|---|---|']
    for p in asr:
        r = json.loads(p.read_text(encoding='utf-8'))
        lines.append(f"| `{r['model']}` | {r['clips']} | {r['cer']:.1%} | {r['wer']:.1%} | {r['median_seconds']} |")
    lines += ['', '- FLEURS records each sentence with several speakers, so the first N clips cover fewer distinct sentences.',
              '- The model\'s own confidence stays near 0.98 even at 14% CER, so "not sure" relies on the other checks '
              '(script, translation length, offer check, numbers), not on confidence.',
              '- Vanilla `openai/whisper-small` writes Malayalam in Latin letters ("Paa Amm Oil, anna dalida maya…") '
              'and is unusable for this; spot-checked on FLEURS clips, not scored.', '']

    cmp = load('asr_compare.json')
    if cmp:
        lines += ['## Speech to text: real voice notes', '', cmp['note'], '',
                  '| Model | Voice notes CER (vs script) | FLEURS 30 CER | Seconds per 18 s note | Licence |',
                  '|---|---|---|---|---|']
        for m in cmp['models']:
            lines.append(f"| `{m['model']}` | {' / '.join(f'{c:.0%}' for c in m['voice_note_cer'])} | "
                         f"{m['fleurs30_cer']:.1%} | {' / '.join(map(str, m['seconds_per_note']))} | {m['licence']} |")
        lines += ['', 'What the listing writer made of each transcript:', '']
        for model, listings in cmp['listing_effect'].items():
            lines += [f'- `{model}`: ' + '; '.join(f'"{x}"' for x in listings)]
        lines += ['', f'Chosen: `{config.ASR_MODEL}` (best on real speech; slower). '
                      'Set `LANTERN_ASR_MODEL=vrclc/Whisper-small-Malayalam` for the faster fallback.', '']

    lines += ['## Listing: how often is it confidently wrong?', '',
              'Malayalam description (text) → listing, scored against labels in `eval/data/listing_cases.jsonl`: '
              '11 business descriptions and 3 that should be held (off-topic, greeting, too short). '
              '**Synthetic cases written by the team**, and the keyword category rules were tuned on them, '
              'so treat the category score as optimistic.', '',
              '"Confidently wrong" = ready for approval but wrong category, a number the host never said, '
              'or a case that should have been held.', '',
              '| Version | Change | Correct | Held correctly | Held, should list | Confidently wrong |',
              '|---|---|---|---|---|---|']
    for fname, change in [('listing_eval_v1.json', 'first version'),
                          ('listing_eval_v2.json', '"is this an offer?" + category definitions'),
                          ('listing_eval_v3.json', 'keyword categories + drop sentences with invented numbers'),
                          ('listing_eval.json', 'description kept only from words she said; place names read from the Malayalam')]:
        r = load(fname)
        if r:
            s = r['summary']
            lines.append(f"| {fname.replace('listing_eval', '').strip('_.json') or 'current'} | {change} | "
                         f"{s['correct_listings']} | {s['held_correctly']} | {s['held_but_should_list']} | "
                         f"**{s['confidently_wrong']}/{s['cases']} ({s['confidently_wrong_rate']:.0%})** |")
    cur = load('listing_eval.json')
    if cur:
        s = cur['summary']
        lines += ['', f"Invented numbers in published listings: "
                      f"{sum(len(c.get('invented_numbers') or []) for c in cur['cases'])}. "
                      f"Price in the price field: {s['price_in_price_field']}. "
                      f"Category accuracy when listed: {s['category_accuracy_when_listed']:.0%}.", '',
                  '| Case | Outcome | Category | Price | English the model saw |', '|---|---|---|---|---|']
        for c in cur['cases']:
            lines.append(f"| {c['id']} | {c['outcome']} | {c.get('category', '')} | {c.get('price') or ''} | "
                         f"{c['transcript_en']} |")

    listing_s = cur['summary']['median_seconds_per_listing'] if cur else None
    asr_s = json.loads(asr[-1].read_text(encoding='utf-8'))['median_seconds'] if asr else None
    lines += ['', '## Speed and cost', '',
              f'- Speech to text: median {asr_s} s per FLEURS clip; the clips are 13.4 s long at the median '
              '(5.6–31.6 s), so about real time on this CPU.' if asr_s else '',
              f'- Translation + listing + German + Malayalam read-back: median {listing_s} s per listing.' if listing_s else '',
              '- No paid API and no GPU: cost per listing is only server CPU time '
              '(seconds above × the server\'s price per second). The plan\'s 30 s target is not met on this laptop CPU.',
              '', '## Known limits', '',
              '- Translation errors pass through: "Kerala meals served" became "Kerala will be handed over to my house", '
              'pepper became "corn"/"pumpkin". Numbers are checked automatically; other invented details are not, '
              'which is why the host hears the listing in Malayalam and approves it.',
              '- Place names outside `ml/pipeline/places.py` can be mistranslated (Edakkal → "gravel cave").',
              '- NLLB-200 and MMS-TTS are non-commercial (CC-BY-NC-4.0); a commercial version needs other models.',
              '- Not yet tested on real voice notes from a host.', '']
    OUT.write_text('\n'.join(l for l in lines if l is not None) + '\n', encoding='utf-8')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
